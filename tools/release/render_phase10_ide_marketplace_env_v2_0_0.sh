#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT_DIR"

OUT_FILE="docs/status/F10_P20_ide_marketplace_env_template.sh"
DIST_DIR="var/releases/v2_0_0/phase10_ide_dist"

usage() {
  cat <<'USAGE'
Usage: render_phase10_ide_marketplace_env_v2_0_0.sh [options]

Options:
  --dist-dir <dir>     IDE distribution root (default: var/releases/v2_0_0/phase10_ide_dist)
  --out <file>         Output env template (default: docs/status/F10_P20_ide_marketplace_env_template.sh)
  --help               Show help
USAGE
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dist-dir)
      shift
      [[ $# -gt 0 ]] || { echo "missing value for --dist-dir" >&2; exit 2; }
      DIST_DIR="$1"
      ;;
    --out)
      shift
      [[ $# -gt 0 ]] || { echo "missing value for --out" >&2; exit 2; }
      OUT_FILE="$1"
      ;;
    -h|--help|help)
      usage
      exit 0
      ;;
    *)
      echo "unknown option: $1" >&2
      usage
      exit 2
      ;;
  esac
  shift || true
done

DIST_PATH="$ROOT_DIR/$DIST_DIR"
JB_ZIP="$(find "$DIST_PATH/jetbrains" -maxdepth 1 -name '*.zip' -type f 2>/dev/null | head -n1 || true)"
VSIX="$(find "$DIST_PATH/vscode" -maxdepth 1 -name '*.vsix' -type f 2>/dev/null | head -n1 || true)"
GH_ZIP="$DIST_PATH/ghidra/nc-ghidra-extension-v2_0_0.zip"

mkdir -p "$(dirname "$OUT_FILE")"

cat > "$OUT_FILE" <<EOF
#!/usr/bin/env bash
# Generated by render_phase10_ide_marketplace_env_v2_0_0.sh
set -euo pipefail

# Optional selectors:
# export NC_IDE_MARKET_OPS=jetbrains,vscode,ghidra
# export NC_IDE_MARKET_ALLOW_PARTIAL=1

# JetBrains Marketplace publish command
export JETBRAINS_TOKEN="REPLACE_ME_JETBRAINS_TOKEN"
export NC_JETBRAINS_PUBLISH_CMD="cd tools/jetbrains/nc-language-plugin && gradle publishPlugin -Pintellij.publish.token=\"\$JETBRAINS_TOKEN\""

# VSCode Marketplace publish command
export VSCODE_TOKEN="REPLACE_ME_VSCODE_TOKEN"
export NC_VSCODE_PUBLISH_CMD="cd tools/vscode/nc-language && npx @vscode/vsce publish --packagePath \"${VSIX:-REPLACE_ME_VSIX}\" -p \"\$VSCODE_TOKEN\""

# Ghidra distribution publish command
export GHIDRA_RELEASE_DIR="REPLACE_ME_GHIDRA_RELEASE_DIR"
export NC_GHIDRA_PUBLISH_CMD="cp \"${GH_ZIP:-REPLACE_ME_GHIDRA_ZIP}\" \"\$GHIDRA_RELEASE_DIR\"/"

bash tools/release/publish_phase10_ide_marketplaces_v2_0_0.sh \\
  --mode execute \\
  \\${NC_IDE_MARKET_OPS:+--ops \\${NC_IDE_MARKET_OPS}} \\
  \\${NC_IDE_MARKET_ALLOW_PARTIAL:+--allow-partial}
EOF

chmod +x "$OUT_FILE"
echo "OK: ide marketplace env template -> $OUT_FILE"
