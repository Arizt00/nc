#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT_DIR"

usage() {
  cat <<'USAGE'
Usage: render_phase10_external_publish_env_v2_0_0.sh [options]

Render runner-specific external publication template with real commands.

Options:
  --dist-root <dir>     Distribution root (default: var/releases/v2_0_0/phase10_p3_dist)
  --channel <name>      stable|beta|nightly (default: stable)
  --runner <name>       linux|windows|macos|all (default: all)
  --out <file>          Output shell template (default: docs/status/F10_external_publish_env_template.sh)
  --help                Show help
USAGE
}

DIST_ROOT="var/releases/v2_0_0/phase10_p3_dist"
CHANNEL="stable"
RUNNER="all"
OUT_FILE="docs/status/F10_external_publish_env_template.sh"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dist-root)
      shift
      [[ $# -gt 0 ]] || { echo "missing value for --dist-root" >&2; exit 2; }
      DIST_ROOT="$1"
      ;;
    --channel)
      shift
      [[ $# -gt 0 ]] || { echo "missing value for --channel" >&2; exit 2; }
      CHANNEL="$1"
      ;;
    --runner)
      shift
      [[ $# -gt 0 ]] || { echo "missing value for --runner" >&2; exit 2; }
      RUNNER="$1"
      ;;
    --out)
      shift
      [[ $# -gt 0 ]] || { echo "missing value for --out" >&2; exit 2; }
      OUT_FILE="$1"
      ;;
    -h|--help|help)
      usage
      exit 0
      ;;
    *)
      echo "unknown option: $1" >&2
      usage
      exit 2
      ;;
  esac
  shift || true
done

case "$CHANNEL" in
  stable|beta|nightly) ;;
  *)
    echo "invalid --channel '$CHANNEL'" >&2
    exit 2
    ;;
esac

case "$RUNNER" in
  linux|windows|macos|all) ;;
  *)
    echo "invalid --runner '$RUNNER' (expected linux|windows|macos|all)" >&2
    exit 2
    ;;
esac

DIST_PATH="$ROOT_DIR/$DIST_ROOT"
PKG="$DIST_PATH/packages"

WIN_MANIFEST_DIR="$PKG/windows/winget/nc/2.0.0"
DEB_FILE="$(find "$PKG/linux" -maxdepth 1 -name '*.deb' -type f | head -n1 || true)"
RPM_FILE="$(find "$PKG/linux" -maxdepth 1 -name '*.rpm' -type f | head -n1 || true)"
BREW_FORMULA="$PKG/macos/brew-tap/Formula/nc-toolchain.rb"

mkdir -p "$(dirname "$OUT_FILE")"

cat > "$OUT_FILE" <<EOF_INNER
#!/usr/bin/env bash
# Generated by render_phase10_external_publish_env_v2_0_0.sh
# Channel: $CHANNEL
# Runner: $RUNNER
# Distribution root: $DIST_ROOT
set -euo pipefail

export NC_PUBLISH_CHANNEL="$CHANNEL"
export NC_PUBLISH_RUNNER="$RUNNER"

# Optional
# export NC_PUBLISH_ALLOW_PARTIAL=1

# -------------------- Linux adapters (deb/rpm) --------------------
export NC_DEB_FILE="${DEB_FILE:-$PKG/linux/REPLACE_ME.deb}"
export NC_RPM_FILE="${RPM_FILE:-$PKG/linux/REPLACE_ME.rpm}"
export NC_DEB_REPO_BASE="\${NC_DEB_REPO_BASE:-\$HOME/nc-repo/deb}"
export NC_RPM_REPO_DIR="\${NC_RPM_REPO_DIR:-\$HOME/nc-repo/rpm}"
export NC_RPM_REMOTE_MIRROR="\${NC_RPM_REMOTE_MIRROR:-}"
export NC_DEB_PUBLISH_CMD="mkdir -p \"\$NC_DEB_REPO_BASE\" && reprepro -b \"\$NC_DEB_REPO_BASE\" includedeb $CHANNEL \"\$NC_DEB_FILE\""
export NC_RPM_PUBLISH_CMD="mkdir -p \"\$NC_RPM_REPO_DIR\" && cp \"\$NC_RPM_FILE\" \"\$NC_RPM_REPO_DIR\"/ && createrepo_c \"\$NC_RPM_REPO_DIR\" && if [ -n \"\$NC_RPM_REMOTE_MIRROR\" ]; then rsync -av \"\$NC_RPM_REPO_DIR\"/ \"\$NC_RPM_REMOTE_MIRROR\"/; fi"

# -------------------- Windows adapter (winget) --------------------
export NC_WINGET_MANIFEST_DIR="${WIN_MANIFEST_DIR}"
export NC_WINGET_SUBMIT_CMD="wingetcreate submit \"\$NC_WINGET_MANIFEST_DIR\""

# -------------------- macOS adapter (brew tap) --------------------
export NC_BREW_FORMULA="${BREW_FORMULA}"
export NC_BREW_TAP_REPO="\${NC_BREW_TAP_REPO:-\$HOME/homebrew-nc-tap}"
export NC_BREW_TAP_PUBLISH_CMD="mkdir -p \"\$NC_BREW_TAP_REPO/Formula\" && cp \"\$NC_BREW_FORMULA\" \"\$NC_BREW_TAP_REPO/Formula/nc-toolchain.rb\" && git -C \"\$NC_BREW_TAP_REPO\" add Formula/nc-toolchain.rb && git -C \"\$NC_BREW_TAP_REPO\" commit -m \"nC 2.0.0\" && git -C \"\$NC_BREW_TAP_REPO\" push origin main"

bash tools/release/run_phase10_external_publish_matrix_v2_0_0.sh \\
  --runner $RUNNER \\
  --channel $CHANNEL \\
  --mode execute \\
  \${NC_PUBLISH_ALLOW_PARTIAL:+--allow-partial}
EOF_INNER

chmod +x "$OUT_FILE"
echo "OK: publish env template -> $OUT_FILE"
